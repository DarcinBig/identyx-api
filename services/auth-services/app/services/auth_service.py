    # --- Register ---------------------------------------------------------------------------

    async def register(self, data: RegisterRequest, device_info: str | None = None) -> AuthResponse:
        """
        Create a user account.

        Flow:
            1. Create the profile in user-service
            2. Hash the password with Argon2id
            3. Store the credential in identyx_auth (auth-service's database)
            4. Generate the tokens via token-service
            5. Create the session in session-service
            6. Generate the HMAC verification token
            7. Store the verification token in user-service
            8. Publish user.registered (email-service sends the verification email)
            9. Return a complete AuthResponse

        If the credential fails after the profile is created,
        a profile rollback is attempted (best effort).
        """
        # Step 1 — Create the profile in user-service
        user_profile = await self._create_user_profile(data)
        user_id = user_profile["id"]

        # Step 2 — Hash the password
        hashed = hash_password(data.password)

        # Step 3 — Store the credential
        try:
            await self.repo.create(
                user_id=user_id,
                hashed_password=hashed,
            )
        except Exception:
            # Rollback best-effort: delete the created profile
            # to avoid a profile without credentials
            await self._delete_user_profile(user_id)
            raise HTTPException(
                status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
                detail="Failed to store credentials. Please try again.",
            )

        # Step 4 — Call token-service
        tokens = await self._generate_tokens(user_id)

        # Step 5 — Create the session
        await self._create_session(
            user_id=user_id,
            refresh_token_hash=tokens["refresh_token_hash"],
            device_info=device_info,
        )

        # Step 6 — Generate the HMAC verification token
        verification_token = generate_verification_token(user_id, purpose=PURPOSE_EMAIL_VERIFICATION)

        # Step 7 — Store the verification token in user-service
        await self._store_verification_token(
            user_id=user_id,
            raw_token=verification_token,
        )

        # Step 8 — Publish the event (email-service sends the verification email)
        await self._publish_user_registered(
            user_id=user_id,
            email=user_profile["email"],
            username=user_profile["username"],
            verification_token=verification_token,
        )

