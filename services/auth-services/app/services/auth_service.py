import httpx
from fastapi import HTTPException, status
from sqlalchemy.ext.asyncio import AsyncSession

from app.repositories.credential_repo import CredentialRepository
from app.schemas.auth import (
    RegisterRequest,
    LoginRequest,
    AuthResponse,
    UserPublic,
    MessageResponse,
)
from app.security.hashing import hash_password, verify_password, needs_rehash
from app.core.config import get_settings

settings = get_settings()

class AuthService:
    """
    Auth-service business logic.

    Orchestration:
        register → user-service (create profile) → hash password → store credentials
        login → user-service (retrieve profile) → verify password → return tokens
        logout → invalidate session (session-service)

    HTTP calls to the user-service via httpx.
    Tokens will be generated by the token-service.
    Sessions will be managed by the session-service.
    """
    def __init__(self, db: AsyncSession):
        self.repo = CredentialRepository(db)

    # --- Internal calls to user service -----------------------------------------------------

    async def _create_user_profile(self, data: RegisterRequest) -> dict:
        """
        Creates the user profile via user-service.
        Returns the created profile as a dictionary.

        Raises:
            409 if email or username is already in use (forwards the user-service error)
            503 if user-service is unavailable
        """
        async with httpx.AsyncClient(timeout=10.0) as client:
            try:
                response = await client.post(
                    f"{settings.user_service_url}/users/",
                    json={
                        "email": data.email,
                        "username": data.username,
                        "password": data.password,
                        # The password is sent for rule validation
                        # in the user-service schema, but it will not be
                        # stored there — only the auth-service stores the hash
                    },
                )
            except httpx.ConnectError:
                raise HTTPException(
                    status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
                    detail="User service is unavailable",
                )
            except httpx.TimeoutException:
                raise HTTPException(
                    status_code=status.HTTP_504_GATEWAY_TIMEOUT,
                    detail="User service timeout",
                )
        if response.status_code == status.HTTP_201_CREATED:
            return response.json()

        # Forward user-service errors (409, 422, etc.)
        raise HTTPException(
            status_code=response.status_code,
            detail=response.json().get("detail", "User creation failed"),
        )

    async def _get_user_by_email(self, email: str) -> dict:
        """
        Retrieves a user profile via email using a user service.
        Used during login.

        Raises:
            404 if the user does not exist
            503 if the user service is unavailable
        """
        async with httpx.AsyncClient(timeout=10.0) as client:
            try:
                response = await client.get(
                    f"{settings.user_service_url}/users/internal/by-email",
                    params={"email": email},
                )
            except httpx.ConnectError:
                raise HTTPException(
                    status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
                    detail="User service is unavailable",
                )
            except httpx.TimeoutException:
                raise HTTPException(
                    status_code=status.HTTP_504_GATEWAY_TIMEOUT,
                    detail="User service timeout",
                )
        if response.status_code == status.HTTP_200_OK:
            return response.json()

        # 404 → unknown email → we say "invalid credentials" to avoid
        # revealing whether the email exists or not (security through obscurity)
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Invalid email or password",
        )

    # --- Register ---------------------------------------------------------------------------

    async def register(self, data: RegisterRequest) -> AuthResponse:
        """
        Create a user account.

        Flow:
            1. Create the profile in user-service (valid email + unique username)
            2. Hash the password with Argon2id
            3. Store the credential in identyx_auth (auth-service's database)
            4. Return the response (tokens = placeholders in token-service)

        If the credential fails after the profile is created,
        a profile rollback is attempted (best effort).
        """
        # Step 1 — Create the profile in user-service
        user_profile = await self._create_user_profile(data)
        user_id = user_profile["id"]

        # Step 2 — Hash the password
        hashed = hash_password(data.password)

        # Step 3 — Store the credential
        try:
            await self.repo.create(
                user_id=user_id,
                hashed_password=hashed,
            )
        except Exception:
            # Rollback best-effort: delete the created profile
            # to avoid a profile without credentials
            await self._delete_user_profile(user_id)
            raise HTTPException(
                status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
                detail="Failed to store credential. Please try again.",
            )

        # Step 4 — Return the answer
        # The real tokens arrive in token-service
        return AuthResponse(
            access_token="",    # TODO Replace with the real token from token service
            refresh_token="",   # TODO token-service
            token_type="Bearer",
            expires_in=settings.access_token_expires_minutes * 60,
            user=UserPublic(
                id=user_profile["id"],
                email=user_profile["email"],
                username=user_profile["username"],
                is_verified=user_profile["is_verified"],
                avatar_url=user_profile["avatar_url"],
                avatar_provider=user_profile["avatar_provider"],
            ),
        )

    async def _delete_user_profile(self, user_id: str) -> None:
        """
        Deletes the user profile (best-effort rollback).
        Called if credential storage fails after profile creation.
        """
        async with httpx.AsyncClient(timeout=10.0) as client:
            try:
                await client.delete(
                    f"{settings.user_service_url}/users/{user_id}",
                )
            except Exception:
                # We log the failure but we don't retry —
                # The main transaction has already failed
                pass

    # --- Login ------------------------------------------------------------------------------

    async def login(self, data: LoginRequest) -> AuthResponse:
        """
        Logs a user.

        Flow:
            1. Retrieve the profile via user-service (by email)
            2. Retrieve the credential from identyx_auth (auth-service's database)
            3. Verify the password with Argon2id
            4. If needs_rehash → silently update the hash
            5. Return the response (tokens = placeholders in token-service)

        Security note:
            - The email address is not revealed (generic 401 response)
            - The timing is constant thanks to Argon2id.
        """
        # Step 1 — Retrieve the profile
        user_profile = await self._get_user_by_email(data.email)
        user_id = user_profile["id"]

        # Step 2 — Retrieve the credential
        credential = await self.repo.get_by_user_id(user_id)
        if not credential:
            # Credential missing — should not occur in production
            # but we protect against inconsistent states
            raise HTTPException(
                status_code=status.HTTP_401_UNAUTHORIZED,
                detail="Invalid email or password",
            )

        # Step 3 — Verify the password
        if not verify_password(data.password, credential.hashed_password):
            raise HTTPException(
                status_code=status.HTTP_401_UNAUTHORIZED,
                detail="Invalid email or password",
            )

        # Step 4 — Update the hash if necessary
        # (Argon2 parameters changed in production)
        if needs_rehash(credential.hashed_password):
            new_hash = hash_password(data.password)
            await self.repo.update_password(
                user_id=user_id,
                new_hashed_password=new_hash,
            )

        # Step 5 — Return the answer
        # The real tokens arrive in token-service
        return AuthResponse(
            access_token="",    # TODO token-service
            refresh_token="",   # TODO token-service
            token_type="Bearer",
            expires_in=settings.access_token_expires_minutes * 60,
            user=UserPublic(
                id=user_profile["id"],
                email=user_profile["email"],
                username=user_profile["username"],
                is_verified=user_profile["is_verified"],
                avatar_url=user_profile["avatar_url"],
                avatar_provider=user_profile["avatar_provider"],
            ),
        )

    # --- Logout -----------------------------------------------------------------------------

