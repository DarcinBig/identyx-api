    async def _get_failed_attempts_count(
            self,
            email: str,
            ip: str,
    ) -> int:
        """
        Reads the current brute-force counter for the email key.
        Returns the number of failed attempts before reset.
        Called from login() BEFORE reset to decide if auth.suspicious
        should be published.
        """
        import redis.asyncio as aioredis

        try:
            client = aioredis.from_url(
                settings.brute_force_redis_url,
                encoding="utf-8",
                decode_responses=True,
            )
            count = await client.get(f"brute:email:{email.lower()}")
            await client.aclose()
            return int(count) if count else 0
        except Exception:
            return 0

    async def _publish_auth_suspicious(
            self,
            user_id: str,
            email: str,
            username: str,
            failed_attempts: int,
    ) -> None:
        """
        Publishes auth.suspicious to Kafka.
        Email-service sends a security alert email.
        Called from login() when a login succeeds after prior failures.
        """
        from app.main import event_publisher

        if not event_publisher:
            return

        event = AuthSuspiciousLoginEvent(
            user_id=user_id,
            email=email,
            username=username,
            failed_attempts=failed_attempts,
        )
        await event_publisher.publish(CHANNEL_AUTH_SUSPICIOUS, event)

    # --- Logout -----------------------------------------------------------------------------

    async def logout(self, refresh_token: str, access_token: str | None = None) -> MessageResponse:
        """
        Disconnects a user.

        Flow:
            1. Revoke the session in session-service (refresh token)
            2. Revoke the access token in token-service (blacklist Redis)
                — best-effort, if access_token is provided

        The client must send the refresh_token.
        The access_token is optional — if provided,
        it is immediately blacklisted in Redis.
        """
        logger.info("logout_started", extra={
            "refresh_token_prefix": refresh_token[:20],
        })

        # Step 1 — Revoke the session
        await self._revoke_session(refresh_token)

        # Step 2 — Revoke the access token (best-effort)
        if access_token:
            await self._revoke_access_token(access_token)
        else:
            logger.warning("logout_no_access_token")

        return MessageResponse(message="Successfully logged out")

    # --- Refresh ----------------------------------------------------------------------------

    async def refresh(self, refresh_token: str) -> AuthResponse:
        """
        Renew tokens with rotation.

        Flow:
            1. Validate the refresh token in the session service
            2. Retrieve the user profile via the user service
            3. Generate a new token pair via the token service
            4. Rotation in the session service:
                old hash replaced by new hash
            5. Return the AuthResponse with the new tokens

        Security:
            Each refresh token can only be used once.
            If an attacker uses a stolen token first,
            the legitimate user will receive a 401 error on the next refresh.
        """
        # Step 1 — Validate the session
        session_data = await self._validate_session(refresh_token)
        if not session_data.get("valid"):
            raise HTTPException(
                status_code=status.HTTP_401_UNAUTHORIZED,
                detail="Invalid or expired refresh token",
            )
        user_id = session_data["user_id"]

        # Step 2 — Retrieve the profile
        user_profile = await self._get_user_by_id(user_id)

        # Step 3 — Generate the new tokens
        tokens = await self._generate_tokens(user_id)

        # Step 4 — Session Rotation
        await self._rotate_session(
            old_refresh_token=refresh_token,
            new_refresh_token_hash=tokens["refresh_token_hash"],
        )

        # Step 5 — Return the new tokens
        return AuthResponse(
            access_token=tokens["access_token"],
            refresh_token=tokens["refresh_token"],
            token_type="Bearer",
            expires_in=tokens["expires_in"],
            user=UserPublic(
                id=user_profile["id"],
                email=user_profile["email"],
                username=user_profile["username"],
                is_verified=user_profile["is_verified"],
                avatar_url=user_profile["avatar_url"],
                avatar_provider=user_profile["avatar_provider"],
            )
        )

    # --- Verify Email -----------------------------------------------------------------------

    async def verify_email(self, raw_token: str) -> VerifyEmailResponse:
        """
        Verifies the HMAC token and marks the email as verified.

        Flow:
            1. Verify the HMAC signature of the token
            2. Retrieve the token in user-service (checks expiration + is_used)
            3. Mark the token as used AND the email as verified in user-service
            4. Return VerifyEmailResponse
        """
        # Step 1 — Verify the HMAC signature
        is_valid, user_id = verify_verification_token(raw_token)
        if not is_valid or not user_id:
            raise HTTPException(
                status_code=status.HTTP_400_BAD_REQUEST,
                detail="Invalid verification token.",
            )

        # Step 2 — Verify the token in DB via user-service
        # (expiration + is_used)
        verify_result = await self._check_verification_token(
            user_id=user_id,
            raw_token=raw_token,
        )

        if not verify_result.get("valid"):
            raise HTTPException(
                status_code=status.HTTP_400_BAD_REQUEST,
                detail=verify_result.get(
                    "detail",
                    "Invalid or expired verification token.",
                ),
            )

        # Step 3 — Mark the token as used and the email as verified
        result = await self._confirm_email_verification(
            user_id=user_id,
            raw_token=raw_token,
        )

        # Step 4 — Return VerifyEmailResponse
        return VerifyEmailResponse(
            message="Email verified successfully.",
            email=result.get("email", ""),
            is_verified=True,
        )
