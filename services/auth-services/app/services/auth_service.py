    # --- Login ------------------------------------------------------------------------------

    async def login(
            self,
            data: LoginRequest,
            device_info: str | None = None,
            client_ip: str = "unknown",
    ) -> AuthResponse:
        """
        Logs in a user with brute-force protection.

        Flow:
            0. Check for brute-force lockout
            1. Retrieve profile via user-service
            2. Retrieve credential
            3. Verify password with Argon2id
                → If failed: log attempt and raise 401
                → If successful: read the failure counter then reset it
            4. needs_rehash → silently update
            5. Generate tokens
            6. Create session
            7. Publish auth.login event
            7b. Publish auth.new_login (email notification with device info)
            8. If there were prior failures → publish auth.suspicious event
            9. Return AuthResponse

        Security note:
            - The email address is not revealed (generic 401 response)
            - The timing is constant(Argon2id).
        """
        from app.security.brute_force import (
            check_brute_force,
            record_failed_attempt,
            reset_brute_force,
        )

        # Step 0 — Check the lockout
        await check_brute_force(
            email=data.email,
            ip=client_ip,
            redis_url=settings.brute_force_redis_url,
            max_attempts=settings.brute_force_max_attempts,
            lockout_minutes=settings.brute_force_lockout_minutes,
        )

        # Step 1 — Retrieve the profile
        user_profile = await self._get_user_by_email(data.email)
        user_id = user_profile["id"]

        # Step 2 — Retrieve the credential
        credential = await self.repo.get_by_user_id(user_id)
        if not credential:
            # A profile exists without credentials → treat as a failed login
            await record_failed_attempt(
                email=data.email,
                ip=client_ip,
                redis_url=settings.brute_force_redis_url,
                lockout_minutes=settings.brute_force_lockout_minutes,
            )
            raise HTTPException(
                status_code=status.HTTP_401_UNAUTHORIZED,
                detail="Invalid email or password",
            )

        # Step 3 — Verify the password
        if not verify_password(data.password, credential.hashed_password):
            # Record the failure before raising the exception
            await record_failed_attempt(
                email=data.email,
                ip=client_ip,
                redis_url=settings.brute_force_redis_url,
                lockout_minutes=settings.brute_force_lockout_minutes,
            )
            raise HTTPException(
                status_code=status.HTTP_401_UNAUTHORIZED,
                detail="Invalid email or password",
            )

        # Read the failure counter BEFORE the reset,
        # to decide if auth.suspicious should be published
        failed_attempts = await self._get_failed_attempts_count(
            email=data.email,
            ip=client_ip,
        )

        # Success — resets the brute-force counter
        await reset_brute_force(
            email=data.email,
            ip=client_ip,
            redis_url=settings.brute_force_redis_url,
        )

        # Step 4 — Update the hash if necessary (need_hash)
        # (Argon2 parameters changed in production)
        if needs_rehash(credential.hashed_password):
            new_hash = hash_password(data.password)
            await self.repo.update_password(
                user_id=user_id,
                new_hashed_password=new_hash,
            )

        # Step 5 — Generate token
        tokens = await self._generate_tokens(user_id)

        # Step 6 — Create the session
        await self._create_session(
            user_id=user_id,
            refresh_token_hash=tokens["refresh_token_hash"],
            device_info=device_info,
        )

        # Step 7 — Publish the login event (fire & forget)
        await self._publish_auth_login(
            user_id=user_id,
            email=user_profile["email"],
        )

        # Step 7b — Notify the user of a new login (multi-device)
        await self._publish_new_login(
            user_id=user_id,
            email=user_profile["email"],
            username=user_profile["username"],
            device_info=device_info or "unknown",
            client_ip=client_ip,
        )

        # Step 8 — Publish a suspicious login event if the account was
        # close to the lockout threshold before this successful login.
        # The event carries an HMAC-signed reset token so the security
        # email can offer a direct, one-time password change link.
        if failed_attempts >= settings.brute_force_max_attempts - 1:
            reset_token = await self._generate_and_store_reset_token(user_id)
            await self._publish_auth_suspicious(
                user_id=user_id,
                email=user_profile["email"],
                username=user_profile["username"],
                failed_attempts=failed_attempts,
                reset_token=reset_token,
            )

        # Step 9 — Return to full AuthResponse
        return AuthResponse(
            access_token=tokens["access_token"],
            refresh_token=tokens["refresh_token"],
            token_type="Bearer",
            expires_in=tokens["expires_in"],
            user=UserPublic(
                id=user_profile["id"],
                email=user_profile["email"],
                username=user_profile["username"],
                is_verified=user_profile["is_verified"],
                avatar_url=user_profile["avatar_url"],
                avatar_provider=user_profile["avatar_provider"],
            ),
        )

